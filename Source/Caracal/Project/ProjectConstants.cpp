#include <Caracal/Project/ProjectConstants.h>
#include <Caracal/Syntax/StringEscapes.h>

namespace Caracal
{
    static std::string StringConstant(std::string_view name, std::string_view value)
    {
        return std::string(name) + " : string : \"" + escapeStringLiteral(value) + "\";\n";
    }

    std::string createProjectConstantsSource(const Project& project)
    {
        return "// generated by the compiler, do not edit\n"
            + StringConstant("__caracal_project_name", project.name)
            + StringConstant("__caracal_project_version", project.version);
    }
}
